async function run() {
  let uri = process.env.MONGODB_URI?.trim()

  if (!uri) {
    console.error('❌ MONGODB_URI is not set in .env.local')
    process.exit(1)
  }

  // Ensure database path exists in URI
  if (uri.endsWith('.mongodb.net/')) {
    uri = `${uri}bup_nest?retryWrites=true&w=majority`
  } else if (uri.endsWith('.mongodb.net')) {
    uri = `${uri}/bup_nest?retryWrites=true&w=majority`
  } else if (!uri.includes('?') && !uri.split('.mongodb.net')[1]?.includes('/')) {
    uri = `${uri}/bup_nest?retryWrites=true&w=majority`
  }

  console.log('🔄 Connecting to MongoDB Atlas...')
  await mongoose.connect(uri, { serverSelectionTimeoutMS: 10000 })
  console.log('✅ Connected to MongoDB Atlas!')
  console.log(`📁 Database: ${mongoose.connection.name || 'bup_nest'}`)

  // 1. Seed Users
  console.log('\n👤 Seeding users...')
  const password = await bcrypt.hash('password123', 10)
  for (const user of DEFAULT_USERS) {
    await UserModel.findOneAndUpdate(
      { email: user.email },
      { $setOnInsert: { ...user, passwordHash: password } },
      { upsert: true, new: true }
    )
  }
  const userCount = await UserModel.countDocuments()
  console.log(`✅ Users collection ready: ${userCount} accounts.`)

  // 2. Fetch users for seller mapping
  const users = await UserModel.find().lean()
  const sellerMap = new Map()
  for (const u of users) {
    if (u.storeName) sellerMap.set(u.storeName, u.customId)
  }
  const defaultCanteenId = sellerMap.get('Central Canteen (Mirpur Cantonment)') || users[0]?.customId

  // 3. Seed Products
  console.log('\n📦 Seeding products collection...')
  let prodInserted = 0
  for (const p of PRODUCTS) {
    const existing = await ProductModel.findOne({
      $or: [{ customId: p.id }, { name: p.name }],
    })
    if (!existing) {
      const sellerId = sellerMap.get(p.seller) || defaultCanteenId
      await ProductModel.create({
        customId: p.id,
        sellerId,
        name: p.name,
        description: p.description,
        category: p.category,
        price: p.price,
        originalPrice: p.originalPrice ?? null,
        image: p.image,
        stock: 50,
        inStock: p.inStock,
        tag: p.tag ?? null,
        deliveryTime: p.deliveryTime,
        rating: p.rating,
        reviewsCount: p.reviewsCount,
        isActive: true,
        mealType: p.mealType ?? null,
      })
      prodInserted++
    }
  }
  const prodCount = await ProductModel.countDocuments()
  console.log(`✅ Products collection ready: ${prodCount} total catalog items (${prodInserted} new).`)

  // 4. Seed Stalls
  console.log('\n🎪 Seeding lake stalls collection...')
  for (const s of STALLS) {
    await StallModel.findOneAndUpdate(
      { stallId: s.id },
      {
        $setOnInsert: {
          stallId: s.id,
          name: s.name,
          zone: s.zone,
          side: s.side,
          status: s.status,
          position: s.position,
          tone: s.tone,
          dailyRate: s.dailyRate,
          features: s.features,
          coordinates: s.coordinates,
          footfall: s.footfall,
          peakHours: s.peakHours,
          ambience: s.ambience,
          image: s.image,
          dimensions: s.dimensions,
          powerGrid: s.powerGrid,
          recommendedFor: s.recommendedFor,
          description: s.description,
          reservedBy: s.reservedBy ?? null,
        },
      },
      { upsert: true }
    )
  }
  const stallCount = await StallModel.countDocuments()
  console.log(`✅ Stalls collection ready: ${stallCount} stalls in Atlas.`)

  console.log('\n🎉 SUCCESS! MongoDB Atlas database "bup_nest" has been populated successfully!')
  console.log('👉 Head over to MongoDB Atlas -> Database -> "Browse Collections" to explore your live collections!')

  await mongoose.disconnect()
  process.exit(0)
}

run().catch((err) => {
  console.error('\n❌ Seeding failed:', err)
  process.exit(1)
})

