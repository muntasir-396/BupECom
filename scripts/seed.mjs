// --- Mongoose Schemas ---
const UserSchema = new mongoose.Schema(
  {
    customId: { type: String, unique: true, index: true, required: true },
    email: { type: String, required: true, unique: true, lowercase: true, trim: true, index: true },
    passwordHash: { type: String, required: true },
    name: { type: String, required: true, trim: true },
    phone: { type: String, default: null },
    role: { type: String, enum: ['BUYER', 'SELLER', 'ADMIN'], default: 'SELLER' },
    studentId: { type: String, default: null },
    department: { type: String, default: null },
    isBupVerified: { type: Boolean, default: false },
    storeName: { type: String, default: null },
    storeDescription: { type: String, default: null },
    sellerType: { type: String, default: null },
  },
  { timestamps: true }
)

const ProductSchema = new mongoose.Schema(
  {
    customId: { type: String, unique: true, index: true, required: true },
    sellerId: { type: String, required: true, index: true },
    name: { type: String, required: true, trim: true, index: true },
    description: { type: String, required: true },
    category: { type: String, required: true, index: true },
    price: { type: Number, required: true, min: 0 },
    originalPrice: { type: Number, default: null },
    image: { type: String, required: true },
    stock: { type: Number, required: true, default: 50, min: 0 },
    inStock: { type: Boolean, default: true, index: true },
    tag: { type: String, default: null },
    deliveryTime: { type: String, default: '2-4 days' },
    rating: { type: Number, default: 0, min: 0, max: 5 },
    reviewsCount: { type: Number, default: 0, min: 0 },
    isActive: { type: Boolean, default: true, index: true },
    mealType: { type: String, default: null, index: true },
  },
  { timestamps: true }
)
ProductSchema.index({ name: 'text', description: 'text', category: 'text' })

const StallSchema = new mongoose.Schema(
  {
    stallId: { type: String, unique: true, index: true, required: true },
    name: { type: String, required: true },
    zone: { type: String, required: true },
    side: { type: String, required: true },
    status: { type: String, default: 'Open' },
    position: { type: String, required: true },
    tone: { type: String, default: 'bg-[#B25D3E]' },
    dailyRate: { type: Number, required: true },
    features: { type: [String], default: [] },
    coordinates: {
      x: { type: Number, required: true },
      y: { type: Number, required: true },
    },
    footfall: { type: String },
    peakHours: { type: String },
    ambience: { type: String },
    image: { type: String },
    dimensions: { type: String },
    powerGrid: { type: String },
    recommendedFor: { type: [String], default: [] },
    description: { type: String },
    reservedBy: { type: String, default: null },
  },
  { timestamps: true }
)

const UserModel = mongoose.models.User || mongoose.model('User', UserSchema)
const ProductModel = mongoose.models.Product || mongoose.model('Product', ProductSchema)
const StallModel = mongoose.models.Stall || mongoose.model('Stall', StallSchema)

